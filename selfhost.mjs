// Self-host Nuvvo's third-party assets (Google Fonts + supabase-js from jsDelivr) so the browser
// only talks to your own domain (plus Supabase and Cloudflare Turnstile).
// Run from the project folder on a computer with Node 18+ and internet:   node tools/selfhost.mjs
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const pub = path.resolve('public');
const tmp = fs.mkdtempSync(path.join(process.env.TEMP || process.env.TMPDIR || '.', 'nuvvo-'));
execSync('npm init -y', { cwd: tmp, stdio: 'ignore' });
execSync('npm i @fontsource/ibm-plex-sans-arabic @fontsource/readex-pro @supabase/supabase-js@2.58.0', { cwd: tmp, stdio: 'inherit' });

const nm = path.join(tmp, 'node_modules');
fs.mkdirSync(path.join(pub, 'vendor', 'fonts'), { recursive: true });
fs.copyFileSync(path.join(nm, '@supabase/supabase-js/dist/umd/supabase.js'), path.join(pub, 'vendor', 'supabase.js'));

let css = '/* generated by tools/selfhost.mjs */\n';
for (const [pkg, weights] of [['ibm-plex-sans-arabic', [400, 500, 600]], ['readex-pro', [500, 600, 700]]]) {
  for (const w of weights) {
    let c = fs.readFileSync(path.join(nm, '@fontsource', pkg, w + '.css'), 'utf8');
    for (const f of c.match(/files\/[^)'"]+\.woff2/g) || []) fs.copyFileSync(path.join(nm, '@fontsource', pkg, f), path.join(pub, 'vendor', 'fonts', path.basename(f)));
    css += c.replace(/url\(\.\/files\//g, 'url(vendor/fonts/').replace(/,\s*url\([^)]*\.woff\)\s*format\(['"]woff['"]\)/g, '') + '\n';
  }
}
fs.writeFileSync(path.join(pub, 'fonts.css'), css);

const patch = (file, fn) => { const p = path.join(pub, file); fs.writeFileSync(p, fn(fs.readFileSync(p, 'utf8'))); };
patch('index.html', (h) => h
  .replace(/<link rel="preconnect" href="https:\/\/fonts\.googleapis\.com">\s*/, '')
  .replace(/<link rel="preconnect" href="https:\/\/fonts\.gstatic\.com" crossorigin>\s*/, '')
  .replace(/<link rel="stylesheet" href="https:\/\/fonts\.googleapis\.com[^>]*>/, '<link rel="stylesheet" href="fonts.css">')
  .replace(/https:\/\/cdn\.jsdelivr\.net\/npm\/@supabase\/supabase-js@[\d.]+\/dist\/umd\/supabase\.js/, 'vendor/supabase.js'));
patch('_headers', (h) => h.replace(' https://cdn.jsdelivr.net', '').replace(' https://fonts.googleapis.com', '').replace("font-src https://fonts.gstatic.com", "font-src 'self'"));
patch('sw.js', (s) => s.includes('fonts.css') ? s : s.replace("'en.js',", "'en.js', 'fonts.css', 'vendor/supabase.js',"));
fs.rmSync(tmp, { recursive: true, force: true });
console.log('Done. Now deploy. Remember to bump the cache name in public/sw.js.');
